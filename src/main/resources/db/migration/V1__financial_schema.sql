CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(320) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    kyc_status VARCHAR(32) NOT NULL DEFAULT 'PENDING' CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_phone_unique UNIQUE (phone)
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    account_type VARCHAR(32) NOT NULL CHECK (account_type IN ('MAIN_WALLET', 'SAVINGS_WALLET', 'CASH_IN', 'CASH_OUT', 'FEE_REVENUE')),
    name VARCHAR(200) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    balance_paise BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT account_owner_type_check CHECK ((account_type IN ('MAIN_WALLET', 'SAVINGS_WALLET') AND user_id IS NOT NULL) OR (account_type IN ('CASH_IN', 'CASH_OUT', 'FEE_REVENUE') AND user_id IS NULL))
);
CREATE INDEX accounts_user_id_id_idx ON accounts(user_id, id);

CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_type VARCHAR(32) NOT NULL CHECK (transfer_type IN ('TOPUP', 'PEER_TRANSFER', 'WITHDRAWAL', 'FEE', 'REVERSAL')),
    status VARCHAR(32) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'HELD', 'REVERSED', 'FAILED')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    source_account_id BIGINT REFERENCES accounts(id),
    destination_account_id BIGINT REFERENCES accounts(id),
    counterparty_reference VARCHAR(200),
    note VARCHAR(1000),
    reversal_of_transfer_id BIGINT REFERENCES transfers(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT transfer_accounts_distinct CHECK (source_account_id IS NULL OR destination_account_id IS NULL OR source_account_id <> destination_account_id),
    CONSTRAINT reversal_requires_original CHECK ((transfer_type = 'REVERSAL' AND reversal_of_transfer_id IS NOT NULL) OR (transfer_type <> 'REVERSAL' AND reversal_of_transfer_id IS NULL))
);
CREATE INDEX transfers_source_created_idx ON transfers(source_account_id, created_at DESC, id DESC);
CREATE INDEX transfers_destination_created_idx ON transfers(destination_account_id, created_at DESC, id DESC);
CREATE UNIQUE INDEX transfers_one_reversal_idx ON transfers(reversal_of_transfer_id) WHERE reversal_of_transfer_id IS NOT NULL;

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id),
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    entry_type VARCHAR(16) NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ledger_entries_account_created_idx ON ledger_entries(account_id, created_at DESC, id DESC);
CREATE INDEX ledger_entries_transfer_idx ON ledger_entries(transfer_id);

CREATE TABLE idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    key UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'FAILED')),
    response_status INTEGER,
    response_body JSONB,
    transfer_id BIGINT REFERENCES transfers(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    CONSTRAINT idempotency_user_key_unique UNIQUE (user_id, key)
);

CREATE TABLE risk_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code VARCHAR(64) NOT NULL UNIQUE,
    description VARCHAR(500) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT true,
    threshold_value BIGINT NOT NULL CHECK (threshold_value >= 0),
    threshold_window_seconds INTEGER CHECK (threshold_window_seconds IS NULL OR threshold_window_seconds > 0),
    action VARCHAR(16) NOT NULL CHECK (action IN ('HOLD', 'FLAG')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE risk_flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id),
    rule_id BIGINT REFERENCES risk_rules(id),
    risk_label VARCHAR(32) NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    llm_label VARCHAR(32),
    llm_explanation VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX risk_flags_transfer_idx ON risk_flags(transfer_id);

CREATE TABLE transfer_status_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id),
    previous_status VARCHAR(32),
    new_status VARCHAR(32) NOT NULL,
    changed_by VARCHAR(200) NOT NULL,
    reason VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX transfer_status_audits_transfer_created_idx ON transfer_status_audits(transfer_id, created_at DESC);

CREATE TABLE reconciliation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    status VARCHAR(32) NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED', 'SKIPPED')),
    checks_executed INTEGER NOT NULL DEFAULT 0,
    problems_found INTEGER NOT NULL DEFAULT 0,
    summary VARCHAR(4000)
);
CREATE TABLE reconciliation_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES reconciliation_runs(id),
    check_code VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id BIGINT,
    expected_value VARCHAR(200),
    actual_value VARCHAR(200),
    description VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX reconciliation_issues_run_idx ON reconciliation_issues(run_id);

