CREATE OR REPLACE FUNCTION reject_ledger_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'ledger_entries are immutable';
END;
$$;
CREATE TRIGGER ledger_entries_immutable_update BEFORE UPDATE OR DELETE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();

CREATE OR REPLACE FUNCTION enforce_wallet_balance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.account_type IN ('MAIN_WALLET', 'SAVINGS_WALLET') AND NEW.balance_paise < 0 THEN
        RAISE EXCEPTION 'wallet balance cannot be negative';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER accounts_non_negative_wallet BEFORE INSERT OR UPDATE OF balance_paise, account_type ON accounts FOR EACH ROW EXECUTE FUNCTION enforce_wallet_balance();

CREATE OR REPLACE FUNCTION enforce_posted_transfer_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    debit_total BIGINT;
    credit_total BIGINT;
    entry_count INTEGER;
    transfer_status VARCHAR(32);
BEGIN
    SELECT status INTO transfer_status FROM transfers WHERE id = NEW.transfer_id;
    IF transfer_status = 'COMPLETED' THEN
        SELECT count(*), COALESCE(sum(amount_paise) FILTER (WHERE entry_type = 'DEBIT'), 0), COALESCE(sum(amount_paise) FILTER (WHERE entry_type = 'CREDIT'), 0)
        INTO entry_count, debit_total, credit_total FROM ledger_entries WHERE transfer_id = NEW.transfer_id;
        IF entry_count < 2 OR debit_total <> credit_total THEN
            RAISE EXCEPTION 'completed transfer % must have balanced ledger entries', NEW.transfer_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER ledger_entries_balanced AFTER INSERT ON ledger_entries DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_posted_transfer_balance();
